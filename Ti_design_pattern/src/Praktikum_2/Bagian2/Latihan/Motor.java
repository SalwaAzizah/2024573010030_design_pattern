package Praktikum_2.Bagian2.Latihan;

public class Motor {
    private String merk;
    private int tahun;

    // Getter merk
    public String getMerk() {
        return merk;
    }

    // Setter merk
    public void setMerk(String merk) {
        this.merk = merk;
    }

    // Getter tahun
    public int getTahun() {
        return tahun;
    }

    // Setter tahun
    public void setTahun(int tahun) {
        this.tahun = tahun;
    }
}
